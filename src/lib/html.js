// Minimal auto-escaping HTML templating.
// Every interpolated value is escaped unless it is a SafeHtml produced by `html` or `raw`.

class SafeHtml {
  constructor(value) {
    this.value = value;
  }
  toString() {
    return this.value;
  }
}

const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;', '`': '&#96;' };

export function escape(value) {
  return String(value).replace(/[&<>"'`]/g, (c) => ESC[c]);
}

function render(value) {
  if (value === null || value === undefined || value === false) return '';
  if (value instanceof SafeHtml) return value.value;
  if (Array.isArray(value)) return value.map(render).join('');
  return escape(value);
}

export function html(strings, ...values) {
  let out = strings[0];
  for (let i = 0; i < values.length; i++) out += render(values[i]) + strings[i + 1];
  return new SafeHtml(out);
}

/** Mark a string as trusted HTML. Only use with content generated by this app. */
export function raw(value) {
  return new SafeHtml(String(value));
}

/** Render plain text with line breaks preserved, safely. */
export function multiline(text) {
  return raw(
    String(text || '')
      .split(/\r?\n/)
      .map(escape)
      .join('<br>'),
  );
}
